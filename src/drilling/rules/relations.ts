import { issue } from '../../domain/index.js';
import type { Issue } from '../../domain/index.js';

/**
 * Недостающая конструктивная связь между деталями (PROMPT 18 §12).
 *
 * ## В чём проблема
 *
 * Присадка полкодержателей идёт не в полку, а в боковину, которая её
 * держит. Присадка направляющей — не в ящик, а в стенку ячейки. Присадка
 * корпусного крепежа — в конкретную пару «боковина ↔ горизонт». Во всех
 * трёх случаях нужно знать, КАКАЯ деталь принимает отверстие.
 *
 * Модель этого не знает. `Part` знает свой узел-источник
 * (`origin.nodeId`) и свои координаты, но связи «эта боковина держит эту
 * полку» в модели нет: дерево секций описывает ПРОСТРАНСТВО, а не стыки.
 *
 * ## Почему это не решается соседством
 *
 * Задание прямо запрещает правило «если два Parts рядом — создать
 * отверстие» (§12), и запрещает справедливо: при вложенных секциях,
 * фальшпанелях и антресоли рядом оказываются детали, которые ничего друг
 * с другом не соединяют, а зеркальная или лишняя присадка — брак, который
 * виден только после сверления.
 *
 * Поэтому правила, которым нужна такая связь, существуют, знают свой вход
 * и честно сообщают, чего не хватает, вместо того чтобы угадывать деталь.
 */
export function missingRelation(what: string, detail: string): Issue {
  return issue('DRILLING_RELATION_NOT_MODELLED', 'warning', `${what} не рассчитана: ${detail}`);
}
