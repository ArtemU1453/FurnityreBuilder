import type { IdFactory } from '../ids.js';
import type { Project, ProjectPreview } from './types.js';

/**
 * Операции над проектом как над целым (PROMPT 25 §9–§11).
 *
 * ## Почему здесь, а не в хранилище
 *
 * Переименовать и продублировать проект — это не «записать байты»,
 * а изменить модель. Хранилище умеет положить и достать; ЧТО именно
 * оно кладёт, решает домен. Если бы дублирование жило в репозитории,
 * оно существовало бы отдельно для IndexedDB и отдельно для памяти —
 * то есть два раза, и разошлось бы при первой же правке.
 *
 * Часы и источник идентификаторов передаются снаружи по той же причине,
 * по которой их принимает `createProject`: домен обязан оставаться
 * чистым и воспроизводимым.
 */

/** Отметка времени изменения. */
export function touchProject(project: Project, now: () => string): Project {
  return { ...project, metadata: { ...project.metadata, updatedAt: now() } };
}

/**
 * Переименование (§10).
 *
 * Идентификатор НЕ меняется — и именно поэтому размещённые в помещении
 * экземпляры продолжают ссылаться на этот проект. Имя показывается,
 * идентификатор ссылается; смешивать эти две роли значило бы ломать
 * расстановку каждым переименованием.
 */
export function renameProject(project: Project, name: string, now: () => string): Project {
  const trimmed = name.trim();
  if (trimmed.length === 0) return project;
  if (trimmed === project.name) return project;
  return touchProject({ ...project, name: trimmed }, now);
}

/**
 * Копия проекта (§11).
 *
 * ## Новый идентификатор — и только он
 *
 * Копия — самостоятельный проект: у неё свой `id`, своё время создания
 * и своя история правок (история живёт в сторе документа и в копию не
 * переносится вовсе). Всё остальное дублируется глубоко, поэтому
 * общих изменяемых ссылок между оригиналом и копией не остаётся:
 * правка ширины в копии не двигает оригинал.
 *
 * ## Внутренние идентификаторы сохраняются намеренно
 *
 * Изделия, узлы, материалы и детали внутри копии оставляют свои id.
 * Они уникальны В ПРЕДЕЛАХ проекта, а ссылка из помещения — это пара
 * «проект + изделие» (`instanceKey`), поэтому совпадение внутренних id
 * у двух проектов ничему не мешает. Перевыпуск всех id, наоборот,
 * стоил бы обхода всего дерева и сломал бы любую ссылку, которую
 * пользователь мог записать себе рядом.
 *
 * Превью не копируется: оно принадлежит состоянию, из которого
 * построено, а у копии это состояние ещё не подтверждено сохранением.
 * Оно построится при первом показе в библиотеке.
 */
export function duplicateProject(
  project: Project,
  ids: IdFactory,
  now: () => string,
  name?: string,
): Project {
  const timestamp = now();
  const clone: Project = structuredClone(project);
  const { preview: _preview, ...rest } = clone;
  return {
    ...rest,
    id: ids.next<'Project'>(),
    name: name ?? copyName(project.name),
    metadata: { ...clone.metadata, createdAt: timestamp, updatedAt: timestamp },
  };
}

/**
 * Имя копии.
 *
 * «Шкаф» → «Шкаф (копия)» → «Шкаф (копия 2)». Второе дублирование не
 * даёт «Шкаф (копия) (копия)»: список из десяти таких имён нечитаем.
 */
export function copyName(name: string): string {
  const match = /^(.*) \(копия(?: (\d+))?\)$/u.exec(name);
  if (match === null) return `${name} (копия)`;
  const base = match[1] ?? name;
  const index = match[2] === undefined ? 2 : Number(match[2]) + 1;
  return `${base} (копия ${String(index)})`;
}

/**
 * Привязка превью к проекту (§8).
 *
 * Превью — производное состояние, и хранится оно только затем, чтобы
 * список библиотеки не пересчитывал геометрию всех проектов ради
 * карточек. Чтобы производное не разошлось с источником, вместе с
 * картинкой хранится отпечаток состояния, из которого она построена:
 * по нему видно, что превью устарело.
 */
export function withPreview(project: Project, preview: ProjectPreview): Project {
  return { ...project, preview };
}
