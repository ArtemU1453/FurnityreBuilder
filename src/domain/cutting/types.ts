import type { Mm } from '../units.js';

/**
 * Параметры раскроя (PROMPT 17 §12, §16–§18).
 *
 * Живут в настройках проекта, а не в слое раскроя: это ВВОД пользователя,
 * который должен переживать сохранение, а не производная величина. Сам
 * раскрой не хранится (§28) — он пересчитывается из деталей и вот этих
 * параметров.
 */

/** Обрезная кромка листа по четырём сторонам (§17). */
export interface TrimSpec {
  readonly left: Mm;
  readonly right: Mm;
  readonly top: Mm;
  readonly bottom: Mm;
}

/**
 * Политика поворота детали на 90° (§18, §26).
 *
 * `by-material` — поворот разрешён, если материал не имеет направления
 * текстуры. `never` — поворот запрещён всегда: так работают производства,
 * которые кладут все детали в одном направлении независимо от декора.
 *
 * Варианта «поворачивать всегда» здесь намеренно нет: он позволил бы
 * положить деталь поперёк текстуры, то есть изготовить заведомо брак ради
 * лучшего процента использования листа.
 */
export type RotationPolicy = 'by-material' | 'never';

export interface CuttingSettings {
  /** Ширина пропила пилы. `ASSUMPTION(T-CUT-01)`. */
  readonly kerf: Mm;
  /** Обрезная кромка листа. По умолчанию берётся из формата листа материала. */
  readonly trim?: TrimSpec;
  readonly rotationPolicy: RotationPolicy;
}

/**
 * ВРЕМЕННОЕ техническое значение ширины пропила, а не производственный
 * норматив: `ASSUMPTION(T-CUT-01)`. Реальная ширина зависит от пилы
 * конкретного цеха (обычно 3–4.4 мм) и референсом не подтверждена. Значение
 * вынесено сюда одной константой именно для того, чтобы его нельзя было
 * встретить «зашитым» в алгоритме раскладки.
 */
export const DEFAULT_KERF: Mm = 4;

export const DEFAULT_CUTTING_SETTINGS: CuttingSettings = {
  kerf: DEFAULT_KERF,
  rotationPolicy: 'by-material',
};

/** Обрезная кромка одинаковой ширины по всем сторонам. */
export function uniformTrim(value: Mm): TrimSpec {
  return { left: value, right: value, top: value, bottom: value };
}
