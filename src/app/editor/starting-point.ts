import type { Furniture } from '../../domain/index.js';
import type { GeometryResult } from '../../geometry/index.js';

/**
 * Что это за объект сейчас и что с ним делают дальше (PROMPT 57 §4–§5, §9).
 *
 * ## Дефект, ради которого модуль появился
 *
 * Аудит PROMPT 53 (`FR-06`): человек открывает приложение и видит
 * готовый объект из пяти деталей под именем «Изделие 1». Ни что это
 * такое, ни что из этого получится, ни что делать после габаритов — не
 * сказано. Поиск по видимому тексту не давал ни одного вхождения слов
 * «шкаф», «с чего начать», «тип изделия».
 *
 * ## Почему здесь НЕТ выбора типа мебели
 *
 * Потому что типов нет. `FurnitureKind` объявляет четыре значения, но
 * читает их во всём проекте одно место — отпечаток для обнаружения
 * изменений, — и ни геометрия, ни производство, ни экспорт по ним не
 * ветвятся. Шкаф, стеллаж, тумба и комод дают побитово одинаковое
 * изделие (`docs/FR06_FURNITURE_STARTING_POINT_ANALYSIS.md`).
 *
 * Предложить выбор значило бы пообещать различие, которого нет: человек,
 * выбравший «Комод», получил бы тот же короб и решил, что приложение
 * сломано. Вместо ветвления — объяснение.
 *
 * ## Состояние ВЫВОДИТСЯ, а не хранится
 *
 * Ни поля «этап», ни флага «новичок», ни счётчика показов. Что человек
 * видит, определяется тем, что он уже построил: пустой короб, разделённый
 * короб, наполненные отделения, закрытые фасадами. Поэтому подпись сама
 * исчезает по мере работы и не нуждается в кнопке «больше не показывать».
 *
 * ## Файл чистый
 *
 * Ни React, ни DOM. Проверяется обычным тестом.
 */

/** Этап сборки, выведенный из фактического состояния изделия. */
export type BuildStage = 'carcass' | 'divided' | 'filled' | 'faced';

export interface StartingPoint {
  readonly stage: BuildStage;
  /** Что это за объект прямо сейчас. */
  readonly what: string;
  /** Следующее осмысленное действие — одной фразой. */
  readonly next: string;
}

/**
 * Что сейчас и что дальше.
 *
 * Порядок проверок идёт от самого построенного к самому пустому:
 * изделие с фасадами — уже не «разделённый короб», хотя и остаётся им.
 */
export function startingPoint(
  furniture: Furniture | undefined,
  geometry: GeometryResult | undefined,
): StartingPoint | undefined {
  if (furniture === undefined || geometry === undefined) return undefined;

  const size = `${formatMm(furniture.dimensions.width)} × ${formatMm(furniture.dimensions.height)} × ${formatMm(furniture.dimensions.depth)} мм`;
  const cells = geometry.cells.length;
  const filled = geometry.cells.filter((cell) => cell.fill.kind !== 'empty').length;
  const facades = furniture.facades.length;

  if (facades > 0) {
    return {
      stage: 'faced',
      what: `Корпус ${size}: отделений ${String(cells)}, фасадов ${String(facades)}.`,
      next: 'Дальше: материалы и раздел «Производство» — там документы для изготовления.',
    };
  }

  if (filled > 0) {
    return {
      stage: 'filled',
      what: `Корпус ${size}: отделений ${String(cells)}, из них занято ${String(filled)}.`,
      next: 'Дальше: закройте отделения дверями — или сразу переходите к производству.',
    };
  }

  if (cells > 1) {
    return {
      stage: 'divided',
      what: `Корпус ${size}, разделён на ${String(cells)} отделения.`,
      next: 'Дальше: щёлкните отделение и положите в него полки или ящики.',
    };
  }

  return {
    stage: 'carcass',
    // Слово «корпус» — из модели, а не придумано: так называется
    // `CarcassSpec`, так подписан шаг 2, и ровно это строит
    // `createDefaultFurniture` — «пустой корпус заданных габаритов».
    what: `Пустой корпус ${size}.`,
    // Из чего он состоит, видно на схеме — перечислять боковины и дно
    // словами значит занимать место тем, что и так перед глазами. На
    // телефоне каждая лишняя строка подписи отнимается у изделия.
    next: 'Дальше: задайте размеры и разделите корпус на отделения.',
  };
}
