import { createShelvesLeaf } from '../../domain/index.js';
import type { IdFactory, LeafFill } from '../../domain/index.js';

/**
 * Одна модель полок для всего интерфейса (PROMPT 60 §3–§6, FR-08).
 *
 * ## Что такое «полки» в модели
 *
 * `LeafFill` с `kind: 'shelves'` — это вид наполнения, у которого есть
 * список отдельных деталей `Shelf`. Отдельного поля «сколько полок» в
 * домене НЕТ: количество — это длина списка. Значит и в интерфейсе
 * второго счётчика заводить нельзя, иначе появится состояние, способное
 * разойтись с моделью.
 *
 * ## Зачем модуль
 *
 * До FR-08 число полок задавалось в одном месте (поле шага «Полки»), а
 * выглядело задаваемым в трёх: переключатель наполнения и кнопка
 * инспектора тоже звали `SetFill` с полками, но с другой семантикой —
 * «сохранить прежнее число, иначе одна». Одинаковые подписи делали
 * разное: кнопка «Добавить полки» на отделении с тремя полками
 * оставляла три, то есть не делала ничего.
 *
 * Разделение теперь названо явно и живёт здесь, а не разбросано по
 * обработчикам:
 *
 * - **сколько полок** — `shelfCountFill`, переходы N → M и N → 0;
 * - **сделать отделение полочным** — `makeShelvesFill`, переход 0 → N.
 *
 * Обе функции зовут одну доменную фабрику `createShelvesLeaf`, поэтому
 * геометрия полок от пути не зависит (§11: правила раскладки не
 * трогаются).
 */

/**
 * Сколько полок в отделении.
 *
 * Читается из единственного места — длины списка деталей. Для любого
 * другого наполнения полок ноль, и это не «пусто»: см.
 * `acceptsShelfCount`.
 */
export function shelfCountOf(fill: LeafFill): number {
  return fill.kind === 'shelves' ? fill.shelves.length : 0;
}

/**
 * Осмысленно ли спрашивать про число полок в этом отделении.
 *
 * Ложно там, где стоит ДРУГОЕ наполнение: у ящика количества полок нет,
 * и показывать для него `0` — врать. Именно так интерфейс и делал: поле
 * шага «Полки» показывало `0` на отделении с ящиком, а ввод любого числа
 * ящик молча уничтожал (§18 E).
 */
export function acceptsShelfCount(fill: LeafFill): boolean {
  return fill.kind === 'empty' || fill.kind === 'shelves';
}

/**
 * Наполнение для заданного числа полок — или `undefined`, если менять
 * нечего.
 *
 * `undefined` означает «команду не отправлять»: либо в отделении стоит
 * чужое наполнение (его нельзя потерять из-за правки числа), либо число
 * уже такое. Ноль — это пустое отделение: полок нет, значит и вида
 * наполнения «полки» нет.
 */
export function shelfCountFill(
  ids: IdFactory,
  fill: LeafFill,
  count: number,
): LeafFill | undefined {
  if (!acceptsShelfCount(fill)) return undefined;
  const next = Math.max(0, Math.round(count));
  if (next === shelfCountOf(fill)) return undefined;
  return next === 0 ? { kind: 'empty' } : createShelvesLeaf(ids, next).fill;
}

/**
 * Наполнение для действия «сделать отделение полочным» (0 → N).
 *
 * Это ДЕЙСТВИЕ, а не параметр: оно отвечает на «пусть здесь будут
 * полки», а не на «сколько». Начальное число — одна полка; дальше его
 * задаёт шаг «Полки». Возвращает `undefined`, когда полки уже есть:
 * тогда действие ничего не значит и предлагать его не следует (§9).
 */
export function makeShelvesFill(ids: IdFactory, fill: LeafFill): LeafFill | undefined {
  if (fill.kind === 'shelves') return undefined;
  return createShelvesLeaf(ids, 1).fill;
}
