/**
 * Какие роли деталей РЕАЛЬНО строит движок для каждого вида наполнения.
 *
 * Не описание намерений, а зафиксированный факт: список сверяется с
 * настоящей геометрией в `tests/unit/app/fill-vocabulary.test.ts`. Он
 * существует ровно затем, чтобы подпись в интерфейсе нельзя было
 * разойтись с тем, что попадает в деталировку.
 *
 * Так уже расходилось: подпись у ящиков утверждала «Ящик добавляет короб
 * и фасад», а короб геометрией не строится — его размеры зависят от типа
 * направляющих, и правило не подтверждено (`T-DRW-05`). Пользователь
 * читал обещание детали, которой в деталировке не появится.
 */
export const FILL_BUILDS: Readonly<Record<(typeof UI_FILL_KINDS)[number], readonly PartRole[]>> = {
  empty: [],
  shelves: ['shelf-adjustable'],
  drawers: ['facade'],
};

