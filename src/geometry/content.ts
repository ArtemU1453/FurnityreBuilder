import type { Drawer, LeafFill, NodeId, Shelf } from '../domain/index.js';

/**
 * Контракт наполнения ячейки: Cell → Content → Parts (PROMPT 9).
 *
 * ## Три разные сущности, которые нельзя смешивать
 *
 * | Сущность | Что это | Где живёт |
 * | --- | --- | --- |
 * | `Part` | физическая деталь: боковина, перегородка, полка, будущая дверь | `GeometryResult.parts` |
 * | `Cell` | пространственная область, а НЕ деталь | `GeometryResult.cells` |
 * | `Content` | логическое наполнение ячейки | `LeafNode.fill` (`LeafFill`) |
 *
 * ## Почему `LeafFill`, а не новый тип
 *
 * Модель наполнения существует с PROMPT 1: `LeafFill` — размеченное
 * объединение (`kind` как дискриминант), лежащее на листе дерева секций.
 * Заводить рядом второй тип `Content` с полем `cellId` означало бы ровно
 * ту параллельную модель, которой проект избегает с самого начала: связь
 * «ячейка → наполнение» пришлось бы поддерживать вручную, а сейчас она
 * структурная — наполнение ЛЕЖИТ внутри ячейки и физически не может от
 * неё оторваться.
 *
 * Отсюда три свойства, которые не нужно обеспечивать — они выполняются
 * по построению:
 *
 * - `content.cellId` всегда корректен: отдельного поля нет, ссылаться
 *   некуда, наполнение достаётся только вместе со своей ячейкой;
 * - осиротевшего наполнения не бывает: удаление ячейки — это удаление
 *   узла дерева вместе со всем, что в нём лежит;
 * - наполнение не может «переехать» в другую ячейку при пересчёте:
 *   пересчёт не трогает дерево.
 *
 * ## Идентичность наполнения
 *
 * У ячейки ровно одно наполнение (см. «одно наполнение на ячейку» ниже),
 * поэтому идентичность наполнения — это идентичность ячейки: `LeafNode.id`.
 * Второго id не заводится по той же причине, по которой у ячейки нет
 * отдельного `cellId` помимо `nodeId` (`docs/DATA_MODEL.md` §5.6).
 * Элементы ВНУТРИ наполнения — полки, ящики, штанга — имеют собственные
 * стабильные `NodeId`, и именно они переживают пересчёт и изменение
 * размеров.
 *
 * ## Одно наполнение на ячейку
 *
 * Правило зафиксировано с PROMPT 1 (`docs/DATA_MODEL.md` §5.5) и остаётся
 * в силе: смешанные случаи выражаются ДЕЛЕНИЕМ ячейки, а не списком
 * наполнений внутри одной. Полки сверху и ящики снизу — это две ячейки,
 * разделённые по оси Y, а не одна ячейка с двумя наполнениями. Так
 * у каждой зоны есть собственные границы, собственный id и собственный
 * размер, а у geometry engine — одно правило вместо разбора комбинаций.
 *
 * Единственное исключение — `rod+shelf`: штанга с полкой над ней. Это не
 * две независимые сущности, а одна типовая конструкция, где полка
 * закрывает штангу сверху; делить её на две ячейки значило бы навязать
 * пользователю разделитель, которого в изделии нет.
 *
 * ## Дверь — не наполнение ячейки
 *
 * `DOOR` из задания в этой модели не является `LeafFill`: фасад может
 * закрывать НЕСКОЛЬКО ячеек сразу, поэтому он живёт отдельно —
 * `Furniture.facades: FacadeGroup[]` с полем `covers`, указывающим на узел
 * дерева или на корпус целиком (`docs/DATA_MODEL.md` §7). Добавить `door`
 * в `LeafFill` значило бы завести второй способ описать ту же дверь и
 * получить два расходящихся источника истины. Геометрия распашных дверей
 * на одну ячейку реализована в PROMPT 10 (`src/geometry/doors.ts`).
 *
 * ## Ящик — наполнение ячейки (в отличие от двери)
 *
 * `DRAWER`, в отличие от `DOOR`, был вариантом `LeafFill` с самого начала
 * (`kind: 'drawers'`): один ящик физически не может обслуживать несколько
 * ячеек сразу — ровно тот случай, где структурная вложенность корректна.
 * PROMPT 11 реализует геометрию его фасада (`src/geometry/drawers.ts`);
 * сам короб (боковины/дно/задняя стенка) остаётся `not-implemented` —
 * схема сборки не подтверждена (`T-DRW-02`, `docs/UNKNOWNS.json`).
 */

/** Вид наполнения. Дискриминант `LeafFill`, а не отдельный перечень. */
export type ContentKind = LeafFill['kind'];

/**
 * Что резолвер смог сделать с наполнением.
 *
 * `not-implemented` — ЯВНЫЙ статус, а не тихий пропуск (PROMPT 9 §9).
 * До этого этапа `fill` молча игнорировал ящики и штангу: наполнение
 * в модели было, деталей не появлялось, и никакого следа об этом не
 * оставалось ни в результате, ни в диагностике.
 */
export type ContentStatus = 'empty' | 'built' | 'not-implemented';

export interface ContentResolution {
  /** Ячейка, к которой относится наполнение. Она же — идентичность наполнения. */
  readonly cellId: NodeId;
  readonly kind: ContentKind;
  readonly status: ContentStatus;
  /**
   * Полки, которые нужно построить в этой ячейке. Пусто для `empty`
   * и для видов, геометрия которых ещё не реализована.
   */
  readonly shelves: readonly Shelf[];
  /**
   * Ящики, которые нужно построить в этой ячейке (PROMPT 11). Пусто для
   * всех видов, кроме `drawers`. Отдельное поле, а не переиспользование
   * `shelves`: `Shelf` и `Drawer` — разные типы, а резолвер лишь передаёт
   * то, что уже лежит в `LeafFill`, не приводя одно к другому.
   */
  readonly drawers: readonly Drawer[];
  /** Человекочитаемое «что именно ещё не строится» — только для `not-implemented`. */
  readonly missing?: string;
}

/**
 * Чистая функция: наполнение ячейки → что из него следует построить.
 *
 * Не читает часы, не обращается к DOM, не зависит от React и не смотрит
 * ни на какое состояние, кроме аргументов: одинаковый вход даёт
 * одинаковый результат. Ни одной геометрической формулы здесь нет —
 * координаты полок считает `stages/fill.ts` из объёма ячейки; эта функция
 * отвечает только на вопрос «что означает это наполнение».
 */
export function resolveContentGeometry(fill: LeafFill, cellId: NodeId): ContentResolution {
  switch (fill.kind) {
    case 'empty':
      // Пустая ячейка не порождает деталей. Это не «нечего строить
      // по недосмотру», а нормальное и самое частое состояние.
      return { cellId, kind: fill.kind, status: 'empty', shelves: [], drawers: [] };

    case 'shelves':
      return {
        cellId,
        kind: fill.kind,
        status: fill.shelves.length === 0 ? 'empty' : 'built',
        shelves: fill.shelves,
        drawers: [],
      };

    case 'rod+shelf':
      // Полка строится (PROMPT 6), сама штанга — ещё нет. Статус честно
      // говорит, что построено не всё, а `missing` — что именно.
      return {
        cellId,
        kind: fill.kind,
        status: 'not-implemented',
        shelves: [fill.shelfAbove],
        drawers: [],
        missing: 'штанга',
      };

    case 'drawers':
      // Фасады ящиков строятся (PROMPT 11) — статус честно отражает,
      // есть ли хоть один ящик, тем же правилом, что и у 'shelves'. Сам
      // короб остаётся не построенным геометрией (см. `drawers.ts`), но
      // это не делает наполнение ячейки в целом not-implemented: фасад —
      // не «часть, которой не хватает», а физически основная, видимая
      // часть ящика.
      return {
        cellId,
        kind: fill.kind,
        status: fill.drawers.length === 0 ? 'empty' : 'built',
        shelves: [],
        drawers: fill.drawers,
      };

    case 'rod':
      return {
        cellId,
        kind: fill.kind,
        status: 'not-implemented',
        shelves: [],
        drawers: [],
        missing: 'штанга',
      };
  }
}

/**
 * Вид наполнения ячейки одним значением — для подписей и статистики.
 * Отдельная функция, чтобы потребителям (например, debug-схеме) не
 * приходилось разбирать `LeafFill` самостоятельно.
 */
export function contentKindOf(fill: LeafFill): ContentKind {
  return fill.kind;
}

/** Русское название вида наполнения для диагностики и подписей. */
export function contentLabel(kind: ContentKind): string {
  switch (kind) {
    case 'empty':
      return 'пусто';
    case 'shelves':
      return 'полки';
    case 'drawers':
      return 'ящики';
    case 'rod':
      return 'штанга';
    case 'rod+shelf':
      return 'штанга с полкой';
  }
}
