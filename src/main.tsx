import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import './design-system/tokens.css';
import { App } from './app/App.js';
import { ErrorBoundary } from './design-system/index.js';
import { collectDiagnostics } from './app/diagnostics.js';

/**
 * Точка входа.
 *
 * ## Почему граница ошибки стоит здесь, а не только внутри приложения
 *
 * Границы вокруг разделов появились на PROMPT 30 и делают своё дело:
 * упавшая сцена не уносит редактор. Но они стоят ВНУТРИ разметки,
 * которую возвращает `App`, — а значит не ловят ничего из того, что
 * происходит до неё: расчёт геометрии в `useMemo`, оболочку,
 * восстановление проекта, саму `App`. Отказ там снимал приложение
 * целиком, и человек видел белый экран без единого слова (PROMPT 45 §3).
 *
 * Пустой `<div id="root">` выглядит в точности как «сайт не работает».
 * Отличить его от отсутствия сети или от ошибки хостинга нельзя, поэтому
 * и написать об этом некому: сообщения нет ни на экране, ни в разговоре
 * с поддержкой.
 *
 * ## Почему здесь есть перезагрузка, а у разделов её нет
 *
 * У раздела остаётся приложение вокруг: можно уйти в другой раздел и
 * вернуться, и это дешевле перезагрузки. Здесь вокруг не осталось
 * ничего — перезагрузка и есть единственное осмысленное действие после
 * «попробовать снова» (PROMPT 45 §12).
 *
 * Автоматически ничего не перезагружается: цикл «загрузилось — упало —
 * перезагрузилось» хуже, чем экран с кнопкой.
 */

const container = document.getElementById('root');
if (container === null) throw new Error('Не найден корневой элемент приложения.');

createRoot(container).render(
  <StrictMode>
    <ErrorBoundary
      title="Приложение столкнулось с непредвиденной ошибкой"
      description="Работу пришлось прервать. Сохранённые проекты при этом не затронуты: они лежат в хранилище браузера, и ошибка их не меняет и не удаляет."
      diagnostics={(error) => collectDiagnostics({ category: 'app', error })}
      onReload={() => {
        window.location.reload();
      }}
    >
      <App />
    </ErrorBoundary>
  </StrictMode>,
);
