#!/usr/bin/env node
/**
 * Страница 404 для статических хостингов (PROMPT 32 §11, §12).
 *
 * ## Зачем она нужна, если у приложения один адрес
 *
 * Адресов у экранов действительно нет — навигация внутренняя
 * (`src/app/shell/AppShell.tsx`). Но пользователь всё равно попадает на
 * несуществующий путь: опечатка в ссылке, старая закладка, чужой
 * переход. Что произойдёт дальше, решает хостинг, и вариантов два.
 *
 * 1. Настроен SPA-fallback — любой путь отдаёт `index.html`, и
 *    приложение просто открывается. Этот файл тогда не используется.
 * 2. Fallback не настроен (GitHub Pages и подобные) — хостинг ищет
 *    `404.html`. Без него человек увидит страницу хостинга, а не нашу.
 *
 * Копия `index.html` закрывает оба случая: на хостингах второго рода
 * приложение откроется и по неизвестному адресу, как и в первом.
 * Поэтому это КОПИЯ, а не страница с надписью «не найдено»: у
 * приложения с одним адресом «не найдено» означает «откройте главную»,
 * и делать за пользователя лишний щелчок незачем.
 *
 * `docs/DEPLOYMENT.md` описывает обе настройки.
 */
import { copyFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DIST = join(process.cwd(), 'dist');
const source = join(DIST, 'index.html');

if (!existsSync(source)) {
  console.error('dist/index.html не найден: сначала сборка, потом этот скрипт.');
  process.exit(1);
}

copyFileSync(source, join(DIST, '404.html'));
console.log('404.html создан как копия index.html (SPA-fallback для хостингов без rewrite).');
