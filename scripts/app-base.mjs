/**
 * Базовый путь приложения — одно место на весь проект (PROMPT 37 §2).
 *
 * ## Зачем он вообще понадобился
 *
 * До PROMPT 37 сборка умела жить только в корне домена, и это было
 * записано как осознанное ограничение: цели размещения в подкаталоге у
 * проекта не заявлялось. Цель появилась — бесплатная публикация на
 * GitHub Pages, а страницы проекта там отдаются по адресу вида
 * `имя.github.io/репозиторий/`. Подкаталог перестал быть возможностью
 * «которой никто не просил» и стал единственным доступным адресом.
 *
 * ## Почему один модуль, а не переменная в трёх местах
 *
 * Базовый путь нужен четырём генераторам сразу: сборке Vite, манифесту,
 * списку предзагрузки service worker'а и проверке готового пакета. Если
 * каждый прочитает переменную окружения по-своему, они разойдутся —
 * и разойдутся молча: приложение в подкаталоге не падает с ошибкой, оно
 * показывает белый экран. Поэтому чтение и нормализация здесь одни.
 *
 * Нормализация обязательна: `/repo`, `repo/` и `/repo/` должны давать
 * один результат, иначе склейка путей даст то `//assets`, то `repoassets`.
 */

/** Нормализованный базовый путь: всегда начинается и заканчивается «/». */
export function appBase(env = process.env) {
  const raw = (env.APP_BASE ?? '').trim();
  if (raw === '' || raw === '/') return '/';
  const withLead = raw.startsWith('/') ? raw : `/${raw}`;
  return withLead.endsWith('/') ? withLead : `${withLead}/`;
}

/** Приклеить базовый путь к пути внутри пакета («assets/x.js»). */
export function withBase(base, path) {
  return `${base}${path.replace(/^\/+/, '')}`;
}
