import { expect, test } from '@playwright/test';

/**
 * Состояние записи проекта говорит человеку, что делать (PROMPT 48, UX-01).
 *
 * ## Что нашёл аудит понятности
 *
 * `STORAGE_STATUS` в `src/app/status.ts` несёт для каждого состояния не
 * только подпись, но и подсказку — что это значит и что делать.
 * Подсказка не показывалась НИГДЕ и ни для одного состояния.
 *
 * Хуже всего это било по отказу записи. Отказ бывает настоящий:
 * переполненная квота, приватный режим, политика организации. Человек
 * видел «Не удалось сохранить» — и не видел единственного совета,
 * который спасал работу: «выгрузите проект файлом». После перезагрузки
 * правки не возвращались.
 *
 * ## Почему отказ вызывается снаружи
 *
 * Запись ломается настоящим отказом браузера — `IDBObjectStore.put`
 * начинает бросать `QuotaExceededError`. В коде приложения нет и не
 * будет ветки «если тест — сломайся»: такой люк однажды выполнится у
 * пользователя.
 */

test('несохранённый проект объясняет, почему автосохранения нет', async ({ page }) => {
  await page.goto('./');
  await page.getByRole('spinbutton', { name: 'Ширина', exact: true }).fill('1234');

  // Подпись говорит ЧТО, подсказка — почему и что делать.
  await expect(page.getByText('Есть несохранённые изменения')).toBeVisible();
  await expect(page.getByText(/Автосохранения нет намеренно/)).toBeVisible();
});

test('отказ записи говорит, как не потерять работу', async ({ page }) => {
  await page.addInitScript(() => {
    // Запись в хранилище отказывает так же, как у человека с полным
    // диском: исключение из самого браузера, а не подмена приложения.
    IDBObjectStore.prototype.put = () => {
      throw new DOMException('Quota exceeded', 'QuotaExceededError');
    };
  });

  await page.goto('./');
  await page.getByRole('spinbutton', { name: 'Ширина', exact: true }).fill('1234');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();

  // Отказ назван…
  await expect(page.getByText('Не удалось сохранить')).toBeVisible({ timeout: 20_000 });

  // …и рядом стоит то, ради чего эта проверка написана: что делать,
  // чтобы не потерять работу. Без этой строки человек закрывал вкладку,
  // считая, что проект где-то есть.
  await expect(page.getByText(/Выгрузите проект файлом/)).toBeVisible();
});
